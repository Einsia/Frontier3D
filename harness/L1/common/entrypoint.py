"""Deterministic standalone launchers for declared L1 Python entrypoints."""

from __future__ import annotations

import keyword
from pathlib import PurePosixPath

ENTRYPOINT_PROTOCOL = "l1-entrypoint-v1"


def entrypoint_mode(entrypoint: str) -> str:
    path = PurePosixPath(entrypoint)
    if entrypoint == "solution.py":
        return "direct"
    parts = (*path.parts[:-1], path.stem)
    if len(parts) > 1 and path.suffix == ".py" and all(p.isidentifier() and not keyword.iskeyword(p) for p in parts):
        return "module"
    return "script"


def launcher_source(entrypoint: str) -> str:
    """Preserve the declared path, imports and __main__ semantics, not its copy.

    This shim is an execution adapter, not a security boundary. Candidate code
    still executes only inside the ordinary candidate Blender process.
    """
    path = PurePosixPath(entrypoint)
    module_name = ".".join((*path.parts[:-1], path.stem))
    mode = entrypoint_mode(entrypoint)
    if mode == "direct":
        raise ValueError("solution.py is already the canonical entrypoint")
    return f'''# Generated by {ENTRYPOINT_PROTOCOL}; declared entrypoint: {entrypoint!r}
import importlib.util as _l1_importlib
from pathlib import Path as _L1Path
import runpy as _l1_runpy
import sys as _l1_sys

_l1_root = _L1Path(__file__).resolve().parent
_l1_entry = _l1_root / {entrypoint!r}
_l1_previous_path = list(_l1_sys.path)
_l1_previous_argv = list(_l1_sys.argv)
try:
    _l1_sys.path[:0] = [str(_l1_entry.parent), str(_l1_root)]
    _l1_sys.argv = [str(_l1_entry)]
    if {mode!r} == "module":
        _l1_spec = _l1_importlib.find_spec({module_name!r})
        if _l1_spec is None or not _l1_spec.origin or _L1Path(_l1_spec.origin).resolve() != _l1_entry.resolve():
            raise ImportError("Declared entrypoint is shadowed or cannot be resolved")
        _l1_runpy.run_module({module_name!r}, run_name="__main__", alter_sys=True)
    else:
        _l1_runpy.run_path(str(_l1_entry), run_name="__main__")
finally:
    _l1_sys.path[:] = _l1_previous_path
    _l1_sys.argv = _l1_previous_argv
'''
